def markdown(blocks: List[Block]) -> str:
    out: List[str] = []
    for block in blocks:
        if block[0] == "h1":
            out += [f"# {block[1]}", ""]
        elif block[0] == "h2":
            out += [f"## {block[1]}", ""]
        elif block[0] == "p":
            out += [block[1], ""]
        else:
            _kind, header, rows = block
            out.append("| " + " | ".join(header) + " |")
            out.append("| " + " | ".join("---" for _ in header) + " |")
            out += ["| " + " | ".join(cell.replace("|", "／") for cell in row) + " |" for row in rows]
            out.append("")
    return "\n".join(out)


